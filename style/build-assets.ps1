$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$assetOutput = Join-Path $PSScriptRoot '../.build/web-assets'
New-Item -ItemType Directory -Force -Path $assetOutput | Out-Null
$header = "#pragma once`n// Generated by style/build-assets.ps1 from the original artwork.`n"
foreach ($asset in @(@{File='favicon.png'; Width=64; Name='PORTAL_ICON'; Output='favicon.png'}, @{File='Background.jpg'; Width=640; Name='PORTAL_BACKGROUND'; Output='background.jpg'})) {
    $source = [System.Drawing.Image]::FromFile((Join-Path $PSScriptRoot $asset.File))
    $height = [int][Math]::Round($source.Height * $asset.Width / $source.Width)
    $bitmap = [System.Drawing.Bitmap]::new($asset.Width, $height)
    $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
    try {
        $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
        $graphics.DrawImage($source, 0, 0, $asset.Width, $height)
        $target = Join-Path $assetOutput $asset.Output
        if ($asset.Output.EndsWith('.png')) { $bitmap.Save($target, [System.Drawing.Imaging.ImageFormat]::Png) }
        else {
            $codec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object MimeType -eq 'image/jpeg'
            $parameters = [System.Drawing.Imaging.EncoderParameters]::new(1)
            $parameters.Param[0] = [System.Drawing.Imaging.EncoderParameter]::new([System.Drawing.Imaging.Encoder]::Quality, [long]65)
            try { $bitmap.Save($target, $codec, $parameters) } finally { $parameters.Dispose() }
        }
        $bytes = [System.IO.File]::ReadAllBytes($target)
        $header += "static const unsigned char $($asset.Name)[] = {`n"
        for ($i=0; $i -lt $bytes.Length; $i+=24) {
            $last = [Math]::Min($i+23, $bytes.Length-1)
            $header += (($bytes[$i..$last] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ',') + ",`n"
        }
        $header += "};`n"
        Write-Output "$($asset.Output): $($bytes.Length) bytes, $($asset.Width)x$height"
    } finally { $graphics.Dispose(); $bitmap.Dispose(); $source.Dispose() }
}
[System.IO.File]::WriteAllText((Join-Path $PSScriptRoot '../btpad_pico/WebAssets.h'), $header, [System.Text.UTF8Encoding]::new($false))
